"""Generate LaTeX tables for the report from result files (no hand-copied numbers).

Usage:  python report/make_tables.py        (run from the project root)
Writes: report/tables_main.tex
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = lambda *p: os.path.join(ROOT, *p)

stats = json.load(open(J("data", "dataset_stats.json")))
crf = json.load(open(J("results", "crf_metrics.json")))
dic = json.load(open(J("results", "dictionary_baseline.json")))
ana = json.load(open(J("results", "error_analysis.json")))


def tab(caption, label, colspec, header, rows, note=None):
    s = ["\\begin{table}[t]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
         f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        s.append((" & ".join(str(c) for c in r) if not isinstance(r, str) else r) + " \\\\" if not (isinstance(r, str) and r == "\\midrule") else "\\midrule")
    s += ["\\bottomrule", "\\end{tabular}"]
    if note:
        s.append(f"\\\\[2pt]{{\\footnotesize {note}}}")
    s.append("\\end{table}")
    return "\n".join(s)


out = []

# ---- dataset statistics
rows = []
for sp, name in [("train", "Train"), ("dev", "Dev"), ("test", "Test")]:
    s = stats[sp]
    m = s["mentions_by_type"]
    rows.append([name, f"{s['sentences']:,}", f"{s['tokens']:,}", f"{s['avg_tokens_per_sentence']:.1f}",
                 f"{m['Chemical']:,}", f"{m['Disease']:,}", f"{s['mentions_total']:,}", f"{s['pct_entity_tokens']:.1f}\\%"])
tot = lambda k: sum(stats[sp][k] for sp in stats)
rows.append("\\midrule")
rows.append(["Total", f"{tot('sentences'):,}", f"{tot('tokens'):,}", "--",
             f"{sum(stats[sp]['mentions_by_type']['Chemical'] for sp in stats):,}",
             f"{sum(stats[sp]['mentions_by_type']['Disease'] for sp in stats):,}", f"{tot('mentions_total'):,}", "--"])
out.append(tab("BC5CDR statistics after preprocessing (sentence-level).", "tab:data", "lrrrrrrr",
               ["Split", "Sent.", "Tokens", "Tok./sent.", "Chem.", "Dis.", "Mentions", "Entity tok."], rows))

# ---- tuning grid (dev F1)
grid = {}
for line in open(J("CRF_paramater_tuning_results.txt")):
    m = re.match(r"c1=([\d.]+) c2=([\d.]+) dev F1=([\d.]+)", line)
    if m:
        grid[(m.group(1), m.group(2))] = float(m.group(3))
best = max(grid, key=grid.get)
c1s, c2s = sorted({k[0] for k in grid}, key=float), sorted({k[1] for k in grid}, key=float)
rows = []
for c1 in c1s:
    cells = []
    for c2 in c2s:
        v = f"{grid[(c1, c2)]:.4f}"
        cells.append(f"\\textbf{{{v}}}" if (c1, c2) == best else v)
    rows.append([f"$c_1={c1}$"] + cells)
out.append(tab("Development-set entity F1 for the nine $(c_1,c_2)$ combinations (best in bold).", "tab:grid",
               "l" + "r" * len(c2s), [""] + [f"$c_2={c}$" for c in c2s], rows))

# ---- main results
def row(name, split, r):
    c, d, o = r["per_type"]["Chemical"], r["per_type"]["Disease"], r["overall"]
    f = lambda x: f"{x:.4f}"
    return [name, split, f(c["precision"]), f(c["recall"]), f(c["f1"]), f(d["precision"]), f(d["recall"]), f(d["f1"]),
            f(o["precision"]), f(o["recall"]), f(o["f1"])]


rows = [row("Dictionary lookup", "test", dic["test"]), row("CRF ($c_1{=}0.1,c_2{=}0.01$)", "dev", crf["dev"]),
        row("CRF ($c_1{=}0.1,c_2{=}0.01$)", "test", crf["test"])]
out.append(tab("Entity-level results (exact span and type match). The CRF is trained on the training split only; "
               "hyperparameters were chosen on dev and the test set was used for the final numbers.",
               "tab:results", "llrrrrrrrrr",
               ["Model", "Split", "P", "R", "F1", "P", "R", "F1", "P", "R", "F1"], rows))
out[-1] = out[-1].replace("\\small", "\\small\\setlength{\\tabcolsep}{3.6pt}", 1)  # keep the 11-column table inside the margins
# add a spanning header by prepending a note line
out[-1] = out[-1].replace("\\toprule",
                          "\\toprule\n & & \\multicolumn{3}{c}{Chemical} & \\multicolumn{3}{c}{Disease} & \\multicolumn{3}{c}{Overall (micro)} \\\\\n"
                          "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}\\cmidrule(lr){9-11}", 1)

with open(J("report", "tables_main.tex"), "w") as f:
    f.write("% AUTO-GENERATED by report/make_tables.py\n" + "\n\n".join(out) + "\n")
for name, t in zip(["data", "grid", "results"], out):  # one file per table, input individually by main.tex
    with open(J("report", f"tables_main_{name}.tex"), "w") as f:
        f.write(t + "\n")
print("wrote report/tables_main*.tex; best grid cell:", best, grid[best])
